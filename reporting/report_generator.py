"""Reproducible Evidence-Linked Report Generator for VERITAS-X."""
import hashlib
import json
from pathlib import Path
from typing import Dict, Any, List, Optional
from core.config import settings
from core.models import Case, CanonicalEvidence, ClaimAssessment, generate_utc_timestamp
from engine.ega import EGAResult

class ReportGenerator:
    """Generates verifiable forensic investigation reports with complete provenance."""

    def __init__(self, reports_dir: Optional[Path] = None):
        self.reports_dir = reports_dir or settings.reports_path
        self.reports_dir.mkdir(parents=True, exist_ok=True)

    def generate_report(
        self,
        case: Case,
        evidence_list: List[CanonicalEvidence],
        ega_result: Optional[EGAResult],
        assessments: List[ClaimAssessment],
        audit_chain_valid: bool,
        audit_record_count: int,
    ) -> Dict[str, Any]:
        """Compile a reproducible forensic investigation report package."""
        timestamp = generate_utc_timestamp()
        report_id = f"rep_{hashlib.sha256(f'{case.case_id}:{timestamp}'.encode()).hexdigest()[:12]}"

        # Construct structured report payload
        report_data: Dict[str, Any] = {
            "schema_version": "1.0.0",
            "report_id": report_id,
            "generated_at": timestamp,
            "case": case.model_dump(),
            "evidence_inventory": [
                {
                    "evidence_id": e.evidence_id,
                    "filename": e.identity.original_filename,
                    "size_bytes": e.identity.size_bytes,
                    "sha256": e.acquisition.original_sha256,
                    "integrity_status": e.integrity.status,
                    "acquired_by": e.acquisition.acquired_by,
                    "acquired_at": e.acquisition.acquired_at,
                    "parser": e.processing.parser,
                }
                for e in evidence_list
            ],
            "evidence_coverage": ega_result.model_dump() if ega_result else None,
            "claim_verifications": [a.model_dump() for a in assessments],
            "integrity_and_audit": {
                "audit_ledger_verified": audit_chain_valid,
                "audit_entries_count": audit_record_count,
                "baseline_evidence_hashes_verified": all(e.integrity.status == "verified" for e in evidence_list),
            },
            "investigator_disclaimer": (
                "This report was deterministically generated by VERITAS-X. All findings are linked "
                "to immutable source records and deterministic predicates. Coverage scores indicate "
                "artifact presence, not guilt. Final conclusions require investigator review."
            ),
        }

        # Calculate reproducible report manifest hash
        manifest_hash = hashlib.sha256(json.dumps(report_data, sort_keys=True).encode()).hexdigest()
        report_data["manifest_sha256"] = manifest_hash

        # Save JSON artifact
        json_path = self.reports_dir / f"{report_id}.json"
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(report_data, f, indent=2)

        # Save Markdown / HTML artifact
        md_path = self.reports_dir / f"{report_id}.md"
        html_path = self.reports_dir / f"{report_id}.html"
        md_content = self._render_markdown(report_data)
        html_content = self._render_html(report_data)

        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_content)
        with open(html_path, "w", encoding="utf-8") as f:
            f.write(html_content)

        return {
            "report_id": report_id,
            "manifest_sha256": manifest_hash,
            "json_path": str(json_path),
            "md_path": str(md_path),
            "html_path": str(html_path),
            "data": report_data,
        }

    def _render_markdown(self, data: Dict[str, Any]) -> str:
        c = data["case"]
        cov = data.get("evidence_coverage") or {}
        lines = [
            f"# VERITAS-X Forensic Investigation Report",
            f"**Report ID:** `{data['report_id']}`  ",
            f"**Generated At:** {data['generated_at']} UTC  ",
            f"**Report Manifest SHA-256:** `{data.get('manifest_sha256')}`  ",
            f"---",
            f"## Case Overview",
            f"- **Case ID:** {c['case_id']}",
            f"- **Title:** {c['title']}",
            f"- **Type:** {c['case_type']}",
            f"- **Description:** {c['description']}",
            f"- **Timezone:** {c['timezone']}",
            f"",
            f"## Evidence Custody & Baseline Hashes",
            f"| Evidence ID | Original Filename | SHA-256 Hash | Integrity Status | Acquired By |",
            f"|---|---|---|---|---|",
        ]
        for e in data["evidence_inventory"]:
            lines.append(f"| `{e['evidence_id']}` | {e['filename']} | `{e['sha256'][:16]}...` | **{e['integrity_status']}** | {e['acquired_by']} |")

        lines.extend([
            f"",
            f"## Evidence Gap Analysis (EGA)",
            f"- **Playbook:** {cov.get('playbook_name', 'N/A')}",
            f"- **Coverage Score:** **{cov.get('coverage_score', 0.0)}%**",
            f"",
            f"### Requirement Status",
        ])
        for req in cov.get("evaluations", []):
            lines.append(f"- **{req['label']}**: `{req['status'].upper()}` ({req['notes']})")

        if cov.get("recommendations"):
            lines.extend([f"", f"### Actionable Investigation Recommendations"])
            for r in cov["recommendations"]:
                lines.append(f"- {r}")

        lines.extend([
            f"",
            f"## Claim-Aware Verification (CAV) Assessments",
        ])
        for a in data["claim_verifications"]:
            lines.extend([
                f"### Claim: `{a['claim_id']}`",
                f"- **Status:** **{a['status'].upper()}**",
                f"- **Supporting Evidence Records:** {', '.join(a.get('supporting_evidence', [])) or 'None'}",
                f"- **Contradictions:** {', '.join(a.get('contradicting_evidence', [])) or 'None'}",
                f"- **Limitations:** {', '.join(a.get('limitations', [])) or 'None'}",
                f"- **Human Review Required:** {a.get('requires_human_review', True)}",
                f"",
            ])

        lines.extend([
            f"## Verification & Audit Integrity",
            f"- Audit Ledger Cryptographic Hash Chain: **{'VALID' if data['integrity_and_audit']['audit_ledger_verified'] else 'COMPROMISED'}**",
            f"- Total Recorded Audit Transactions: **{data['integrity_and_audit']['audit_entries_count']}**",
            f"- All Evidence Hashes Verified: **{'YES' if data['integrity_and_audit']['baseline_evidence_hashes_verified'] else 'NO'}**",
            f"",
            f"> *{data['investigator_disclaimer']}*",
        ])
        return "\n".join(lines)

    def _render_html(self, data: Dict[str, Any]) -> str:
        c = data["case"]
        cov = data.get("evidence_coverage") or {}
        cov_score = cov.get("coverage_score", 0.0)

        html = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>VERITAS-X Report {data['report_id']}</title>
<style>
  body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; background: #0f172a; color: #f8fafc; padding: 2rem; margin: 0; }}
  .container {{ max-width: 900px; margin: 0 auto; background: #1e293b; padding: 2rem; border-radius: 8px; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.5); }}
  h1 {{ color: #38bdf8; border-bottom: 2px solid #334155; padding-bottom: 0.5rem; }}
  h2 {{ color: #94a3b8; margin-top: 1.5rem; border-bottom: 1px solid #334155; padding-bottom: 0.3rem; }}
  .badge {{ display: inline-block; padding: 0.25rem 0.5rem; border-radius: 4px; font-weight: bold; font-size: 0.85rem; }}
  .badge-success {{ background: #065f46; color: #34d399; }}
  .badge-warning {{ background: #78350f; color: #fcd34d; }}
  .badge-danger {{ background: #881337; color: #fda4af; }}
  table {{ width: 100%; border-collapse: collapse; margin-top: 1rem; }}
  th, td {{ padding: 0.6rem; border: 1px solid #334155; text-align: left; }}
  th {{ background: #0f172a; color: #94a3b8; }}
  .hash {{ font-family: monospace; font-size: 0.85rem; color: #38bdf8; word-break: break-all; }}
  .card {{ background: #0f172a; border: 1px solid #334155; border-radius: 6px; padding: 1rem; margin-top: 1rem; }}
  .score {{ font-size: 2rem; font-weight: bold; color: #38bdf8; }}
</style>
</head>
<body>
<div class="container">
  <h1>VERITAS-X Digital Forensics Report</h1>
  <p><strong>Report ID:</strong> <span class="hash">{data['report_id']}</span></p>
  <p><strong>Generated At:</strong> {data['generated_at']} UTC</p>
  <p><strong>Manifest SHA-256:</strong> <span class="hash">{data.get('manifest_sha256')}</span></p>

  <h2>Case Overview</h2>
  <p><strong>Case ID:</strong> {c['case_id']} | <strong>Type:</strong> {c['case_type']}</p>
  <p><strong>Title:</strong> {c['title']}</p>
  <p><strong>Description:</strong> {c['description']}</p>

  <h2>Evidence Inventory & Provenance</h2>
  <table>
    <tr><th>Evidence ID</th><th>Filename</th><th>Size</th><th>SHA-256 Baseline</th><th>Status</th></tr>
"""
        for e in data["evidence_inventory"]:
            html += f"<tr><td><code>{e['evidence_id']}</code></td><td>{e['filename']}</td><td>{e['size_bytes']} B</td><td class='hash'>{e['sha256']}</td><td><span class='badge badge-success'>{e['integrity_status']}</span></td></tr>\n"

        html += f"""
  </table>

  <h2>Evidence Gap Analysis</h2>
  <div class="card">
    <div>Evidence Coverage Score</div>
    <div class="score">{cov_score}%</div>
    <p>Playbook: <strong>{cov.get('playbook_name', 'N/A')}</strong></p>
  </div>

  <h2>Claim Verification Assessments</h2>
"""
        for a in data["claim_verifications"]:
            badge_class = "badge-success" if a['status'] == "supported" else ("badge-warning" if "partially" in a['status'] else "badge-danger")
            html += f"""
  <div class="card">
    <p><strong>Claim ID:</strong> <code>{a['claim_id']}</code> <span class="badge {badge_class}">{a['status'].upper()}</span></p>
    <p><strong>Supporting Records:</strong> {', '.join(a.get('supporting_evidence', [])) or 'None'}</p>
    <p><strong>Limitations:</strong> {', '.join(a.get('limitations', [])) or 'None'}</p>
  </div>
"""

        html += f"""
  <h2>Audit & Ledger Verifiability</h2>
  <p>Audit Ledger Hash Chain: <span class="badge badge-success">{"VERIFIED IMMUTABLE" if data['integrity_and_audit']['audit_ledger_verified'] else "TAMPER DETECTED"}</span></p>
  <p>Recorded Audit Ledger Entries: <strong>{data['integrity_and_audit']['audit_entries_count']}</strong></p>
  <hr style="border-color:#334155; margin-top:2rem;">
  <p style="font-size:0.8rem; color:#64748b;"><em>{data['investigator_disclaimer']}</em></p>
</div>
</body>
</html>"""
        return html

report_generator = ReportGenerator()
